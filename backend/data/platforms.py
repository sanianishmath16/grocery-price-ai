def get_search_url(platform_id: str, query: str) -> str:
    platform = PLATFORM_BY_ID.get(platform_id)
    if not platform:
        return ""
    encoded = urllib.parse.quote_plus(query)
    return platform["search_url_template"].format(query=encoded)


